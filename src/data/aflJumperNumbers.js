export function getPlayerJumperNumber(player) {
  if (!player?.name) return null;
  const matches = aflJumperNumbers.filter((entry) => entry.name === player.name);
  if (matches.length === 1) return matches[0].number;
  const clubMatches = matches.filter((entry) => normalizeTeam(entry.team) === normalizeTeam(player.club));
  return clubMatches.length === 1 ? clubMatches[0].number : null;
}
